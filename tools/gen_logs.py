#!/usr/bin/env python3
"""wakes-sp1 -- the built-in logging defaults, from config/logs.cnfg (#52).

    gen_logs.py <logs.cnfg> <out.h>      build step (CMake runs this)

config/logs.cnfg is the DEFAULT: what Wakes does when the drive has no WAKES/CNFG/logs.cnfg,
or a line in it cannot be read. End users edit the copy on the drive, which the firmware
writes from this same file when it is missing -- so out.h carries the file's text too (SP1_LOGS_TEMPLATE).

The build fails, naming the line, on anything invalid: a default that half-works is worse
than one that refuses to build (gen_audio.py's rule). The device reads the drive's copy with
its own reader (firmware/src/sp1_cnfg.c), which never fails: a bad line keeps its default.
tools/host-tests/cnfgtest.c runs that reader over this file and checks it agrees.

Standard library only. Read as UTF-8 (with or without a BOM).
"""
import configparser
import os
import re
import sys

KEYS = ['enabled', 'performance', 'controls', 'midi', 'usb', 'storage']
CATS = {'performance': 'SP1_LOG_PERFORMANCE', 'controls': 'SP1_LOG_CONTROLS',
        'midi': 'SP1_LOG_MIDI', 'usb': 'SP1_LOG_USB', 'storage': 'SP1_LOG_STORAGE'}
ONOFF = {'on': 1, 'off': 0}
LINE_MAX = 160                       # SP1_CNFG_LINE_MAX: the device ignores longer lines


def fail(path, line, msg):
    where = '%s:%d' % (path, line) if line else path
    sys.stderr.write('\n%s: error: %s\n\n'
                     'The built-in logging defaults are checked at build time. See the\n'
                     'comments in config/logs.cnfg.\n' % (where, msg))
    sys.exit(1)


def line_of(text, section, key):
    cur = None
    for i, ln in enumerate(text.splitlines(), 1):
        s = ln.strip()
        m = re.match(r'^\[(.+)\]$', s)
        if m:
            cur = m.group(1).strip().lower()
        elif cur == section and re.match(r'^%s\s*=' % re.escape(key), s, re.I):
            return i
    return 0


def parse(path):
    with open(path, encoding='utf-8-sig') as f:
        text = f.read()
    if not text.lstrip().startswith(';'):
        fail(path, 1, 'the file must start with a comment naming its format ("; Format: ini")')
    for i, ln in enumerate(text.splitlines(), 1):
        if len(ln.encode('utf-8')) > LINE_MAX:
            fail(path, i, 'line is over %d bytes: the device would ignore it' % LINE_MAX)
    cp = configparser.ConfigParser(inline_comment_prefixes=(';', '#'),
                                   comment_prefixes=(';', '#'), strict=True,
                                   interpolation=None)
    try:
        cp.read_string(text, source=path)
    except configparser.Error as e:
        fail(path, getattr(e, 'lineno', 0), str(e).splitlines()[0])
    for sec in cp.sections():
        if sec != 'logs':
            fail(path, 0, 'unknown section [%s] (expected [logs])' % sec)
    logs = cp['logs'] if cp.has_section('logs') else {}
    cfg = {}
    for key in logs:
        if key not in KEYS:
            fail(path, line_of(text, 'logs', key), 'unknown setting "%s" (expected %s)'
                 % (key, ', '.join(KEYS)))
    for key in KEYS:
        v = logs.get(key, 'on').strip().lower()
        if v not in ONOFF:
            fail(path, line_of(text, 'logs', key), '%s must be on or off, not "%s"' % (key, v))
        cfg[key] = ONOFF[v]
    return cfg, text


def c_string(text):
    """The text as C string literals, one per line; non-ASCII as octal escapes (a hex escape
    would swallow the hex digits after it)."""
    out = []
    for ln in text.splitlines(keepends=True):
        s = ''
        for b in ln.encode('utf-8'):
            c = chr(b)
            if c == '\\':
                s += '\\\\'
            elif c == '"':
                s += '\\"'
            elif c == '\n':
                s += '\\n'
            elif c == '\t':
                s += '\\t'
            elif 0x20 <= b < 0x7f:
                s += c
            else:
                s += '\\%03o' % b
        out.append('\t"%s"' % s)
    return '\n'.join(out) if out else '\t""'


def header(cfg, text):
    cats = [CATS[k] for k in CATS if cfg[k]]
    return '\n'.join([
        '/* GENERATED by tools/gen_logs.py from config/logs.cnfg -- do not edit. */',
        '#pragma once',
        '',
        '/* The built-in defaults (sp1_cnfg.h: SP1_LOG_*). */',
        '#define SP1_LOGS_DEF_ENABLED %d' % cfg['enabled'],
        '#define SP1_LOGS_DEF_CATS    (%s)' % (' | '.join(cats) if cats else '0u'),
        '',
        '/* config/logs.cnfg as the firmware writes it to WAKES/CNFG/ when it is missing; sp1_store.c',
        ' * defines SP1_CNFG_TEMPLATES before including this (no other file has a use for it). */',
        '#if defined(SP1_CNFG_TEMPLATES)',
        'static const char SP1_LOGS_TEMPLATE[] =',
        c_string(text) + ';',
        '#endif',
        '',
    ])


def main():
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        sys.exit(2)
    src, out = sys.argv[1], sys.argv[2]
    cfg, text = parse(src)
    text = header(cfg, text.replace('\r\n', '\n'))
    try:
        with open(out, encoding='utf-8') as f:
            if f.read() == text:
                return          # unchanged: do not force a rebuild
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
